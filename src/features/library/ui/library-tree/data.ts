import type { TreeNodeData } from '@mantine/core'

function createSongs(albumId: string, songs: string[]): TreeNodeData[] {
  return songs.map((song, i) => ({
    label: song,
    value: `${albumId}/song-${i + 1}`,
  }))
}

function createAlbums(bandId: string, albums: { name: string; songs: string[] }[]): TreeNodeData[] {
  return albums.map((album, i) => {
    const albumId = `${bandId}/album-${i + 1}`
    return {
      label: album.name,
      value: albumId,
      children: createSongs(albumId, album.songs),
    }
  })
}

function createBand(name: string, albums: { name: string; songs: string[] }[]): TreeNodeData {
  const bandId = name.toLowerCase().replace(/\s+/g, '-')
  return {
    label: name,
    value: bandId,
    children: createAlbums(bandId, albums),
  }
}

